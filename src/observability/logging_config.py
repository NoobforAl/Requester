"""Structured JSON logging with structlog on top of the stdlib ``logging`` module.

Every log line, whether it comes from ``structlog.get_logger()`` or from a plain
stdlib logger (Django, Celery, gunicorn, third-party libraries), goes through the
same processor chain and the same stdout handler. The schema is documented in
``docs/log-schema.md``.

Usage in settings::

    configure_structlog(LOG_LEVEL, LOG_FORMAT)
    LOGGING = build_logging(LOG_LEVEL, LOG_FORMAT)
"""

from __future__ import annotations

import hashlib
import os
import re
import sys
import traceback
from collections.abc import Callable, Mapping
from datetime import UTC, datetime
from typing import Any

import structlog
from structlog.typing import EventDict, Processor, WrappedLogger

try:  # OTel is optional: without it trace_id/span_id are simply null.
    from opentelemetry import trace as otel_trace
except ImportError:  # pragma: no cover - opentelemetry-api is a dependency
    otel_trace = None  # type: ignore[assignment]

REQUIRED_FIELDS = (
    "timestamp",
    "level",
    "event",
    "service",
    "environment",
    "version",
    "logger",
    "request_id",
    "trace_id",
    "span_id",
)

REDACTED = "[REDACTED]"
CARD_MASK = "[REDACTED_CARD]"
SENSITIVE_KEYS = (
    "password",
    "passwd",
    "secret",
    "token",
    "api_key",
    "authorization",
    "cookie",
    "sessionid",
    "csrftoken",
    "card_number",
    "cvv",
)
# Fields whose values are generated by us and never need scanning.
_SAFE_KEYS = frozenset(
    {"timestamp", "level", "logger", "request_id", "trace_id", "span_id", "task_id"}
)
# Stdlib ``extra`` values that are objects, not data (``django.request`` and
# ``django.server`` attach the request itself). Their repr holds the raw URL.
_DROPPED_EXTRA_KEYS = ("request", "server_time")

_EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
# 13 to 19 digits, optionally separated by single spaces or dashes.
_CARD_RE = re.compile(r"(?<!\d)(?:\d[ -]?){12,18}\d(?!\d)")

THIRD_PARTY_WARNING_LOGGERS = ("httpx", "urllib3", "elasticsearch", "elastic_transport")
ROUTED_LOGGERS = (
    "django",
    "django.server",
    "django.request",
    "gunicorn.error",
    "gunicorn.access",
    "celery",
    "celery.task",
)


# --- processors -------------------------------------------------------------


def hash_email(value: str) -> str:
    """Stable, non-reversible stand-in for an e-mail address."""
    digest = hashlib.sha256(value.strip().lower().encode()).hexdigest()
    return f"sha256:{digest[:12]}"


def add_timestamp(_: WrappedLogger, __: str, event_dict: EventDict) -> EventDict:
    """ISO-8601 UTC timestamp with milliseconds and a ``Z`` suffix."""
    now = datetime.now(UTC)
    event_dict["timestamp"] = now.strftime("%Y-%m-%dT%H:%M:%S.") + (
        f"{now.microsecond // 1000:03d}Z"
    )
    return event_dict


def static_fields_processor() -> Processor:
    """Add ``service``, ``environment`` and ``version`` (read once, from env)."""
    fields = {
        "service": os.environ.get("SERVICE_NAME", "web"),
        "environment": os.environ.get("APP_ENVIRONMENT") or "development",
        "version": os.environ.get("APP_VERSION") or "0.1.0",
    }

    def add_static_fields(
        _: WrappedLogger, __: str, event_dict: EventDict
    ) -> EventDict:
        for key, value in fields.items():
            event_dict.setdefault(key, value)
        return event_dict

    return add_static_fields


def add_trace_context(_: WrappedLogger, __: str, event_dict: EventDict) -> EventDict:
    """``trace_id`` (32 hex) and ``span_id`` (16 hex) of the current OTel span."""
    trace_id = span_id = None
    if otel_trace is not None:
        context = otel_trace.get_current_span().get_span_context()
        if context.is_valid:
            trace_id = format(context.trace_id, "032x")
            span_id = format(context.span_id, "016x")
    if trace_id is not None:
        event_dict["trace_id"] = trace_id
        event_dict["span_id"] = span_id
    return event_dict


def _exc_tuple(exc_info: Any) -> tuple[Any, Any, Any] | None:
    if isinstance(exc_info, BaseException):
        return (type(exc_info), exc_info, exc_info.__traceback__)
    if isinstance(exc_info, tuple):
        return exc_info if exc_info[0] is not None else None
    if exc_info:
        info = sys.exc_info()
        return info if info[0] is not None else None
    return None


def add_exception_fields(_: WrappedLogger, __: str, event_dict: EventDict) -> EventDict:
    """Turn ``exc_info`` into ``exc_type``, ``exc_message`` and ``stack`` (str)."""
    info = _exc_tuple(event_dict.pop("exc_info", None))
    stack_info = event_dict.pop("stack_info", None)
    if info is not None:
        exc_type, exc_value, exc_tb = info
        event_dict["exc_type"] = exc_type.__name__
        event_dict["exc_message"] = str(exc_value)
        event_dict["stack"] = "".join(
            traceback.format_exception(exc_type, exc_value, exc_tb)
        )
    elif isinstance(stack_info, str):
        event_dict["stack"] = stack_info
    elif stack_info:
        event_dict["stack"] = "".join(traceback.format_stack())
    return event_dict


def drop_object_extras(_: WrappedLogger, __: str, event_dict: EventDict) -> EventDict:
    """Remove stdlib ``extra`` objects that are not log data (see above)."""
    if "_record" in event_dict and not event_dict.get("_from_structlog"):
        for key in _DROPPED_EXTRA_KEYS:
            event_dict.pop(key, None)
    return event_dict


def add_required_fields(_: WrappedLogger, __: str, event_dict: EventDict) -> EventDict:
    """Every required field is present; missing ones are null."""
    for key in REQUIRED_FIELDS:
        event_dict.setdefault(key, None)
    return event_dict


def _to_int(value: Any) -> int | None:
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def coerce_types(_: WrappedLogger, __: str, event_dict: EventDict) -> EventDict:
    """Fixed types: ``status_code`` int, ``duration_ms`` float, ``user_id`` int."""
    if "status_code" in event_dict:
        event_dict["status_code"] = _to_int(event_dict["status_code"])
    if "duration_ms" in event_dict:
        try:
            event_dict["duration_ms"] = float(event_dict["duration_ms"])
        except (TypeError, ValueError):
            event_dict["duration_ms"] = None
    if "user_id" in event_dict:
        event_dict["user_id"] = _to_int(event_dict["user_id"])
    return event_dict


def _is_sensitive(key: str) -> bool:
    lowered = key.lower()
    return any(word in lowered for word in SENSITIVE_KEYS)


def _scrub_string(value: str) -> str:
    value = _EMAIL_RE.sub(lambda match: hash_email(match.group(0)), value)
    return _CARD_RE.sub(CARD_MASK, value)


def _redact_value(key: str, value: Any) -> Any:
    if _is_sensitive(key):
        return REDACTED
    if "email" in key.lower() and isinstance(value, str) and value:
        return hash_email(value)
    return _redact_any(value)


def _redact_any(value: Any) -> Any:
    if isinstance(value, str):
        return _scrub_string(value)
    if isinstance(value, Mapping):
        return {k: _redact_value(str(k), v) for k, v in value.items()}
    if isinstance(value, list | tuple | set):
        return [_redact_any(item) for item in value]
    return value


def redact(_: WrappedLogger, __: str, event_dict: EventDict) -> EventDict:
    """Mask secrets, hash e-mail addresses and mask card-like numbers."""
    for key in list(event_dict):
        if key.startswith("_") or key in _SAFE_KEYS:
            continue
        event_dict[key] = _redact_value(key, event_dict[key])
    return event_dict


def shared_processors() -> list[Processor]:
    """The chain used both for structlog calls and for foreign stdlib records."""
    return [
        structlog.contextvars.merge_contextvars,
        structlog.stdlib.add_log_level,
        structlog.stdlib.add_logger_name,
        structlog.stdlib.ExtraAdder(),
        drop_object_extras,
        structlog.stdlib.PositionalArgumentsFormatter(),
        add_timestamp,
        static_fields_processor(),
        add_trace_context,
        add_exception_fields,
        add_required_fields,
        coerce_types,
        redact,
    ]


def _renderer(fmt: str) -> Processor:
    if fmt == "console":
        return structlog.dev.ConsoleRenderer(colors=False)
    return structlog.processors.JSONRenderer(sort_keys=False)


# --- public API -------------------------------------------------------------


def configure_structlog(level: str = "INFO", fmt: str = "json") -> None:
    """Route ``structlog.get_logger()`` calls into stdlib logging.

    Rendering happens once, in the stdlib handler's ``ProcessorFormatter``
    (built by :func:`build_logging`), so structlog and stdlib lines look the same.
    ``level`` and ``fmt`` are accepted for symmetry; filtering is done by the
    stdlib logger levels.
    """
    del level, fmt
    structlog.configure(
        processors=[
            structlog.stdlib.filter_by_level,
            *shared_processors(),
            structlog.stdlib.ProcessorFormatter.wrap_for_formatter,
        ],
        logger_factory=structlog.stdlib.LoggerFactory(),
        wrapper_class=structlog.stdlib.BoundLogger,
        context_class=dict,
        cache_logger_on_first_use=False,
    )


def formatter_config(fmt: str) -> dict[str, Any]:
    """dictConfig entry for the shared ``ProcessorFormatter``."""
    remove_meta: Callable[..., EventDict] = (
        structlog.stdlib.ProcessorFormatter.remove_processors_meta
    )
    return {
        "()": structlog.stdlib.ProcessorFormatter,
        "processors": [remove_meta, _renderer(fmt)],
        "foreign_pre_chain": shared_processors(),
    }


def build_logging(level: str = "INFO", fmt: str = "json") -> dict[str, Any]:
    """Django ``LOGGING`` dictConfig: one stdout handler, one formatter.

    ``fmt`` is ``json`` (production) or ``console`` (human-readable, for DEBUG).
    All named loggers propagate to root, so each record is written exactly once.
    """
    level = (level or "INFO").upper()
    fmt = "console" if fmt == "console" else "json"
    loggers: dict[str, dict[str, Any]] = {
        name: {"handlers": [], "level": level, "propagate": True}
        for name in ROUTED_LOGGERS
    }
    # 4xx/5xx records from django.request go through the same JSON formatter.
    loggers["django.request"]["level"] = "WARNING"
    for name in THIRD_PARTY_WARNING_LOGGERS:
        loggers[name] = {"handlers": [], "level": "WARNING", "propagate": True}
    return {
        "version": 1,
        "disable_existing_loggers": False,
        "formatters": {fmt: formatter_config(fmt)},
        "handlers": {
            "stdout": {
                "class": "logging.StreamHandler",
                "stream": "ext://sys.stdout",
                "formatter": fmt,
            },
        },
        "root": {"handlers": ["stdout"], "level": level},
        "loggers": loggers,
    }
